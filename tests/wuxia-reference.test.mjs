import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (path) => readFileSync(path, 'utf8')
test('all routes share the approved shell without removing the identity provider or global search', () => {
  const shell = read('app/components/LayoutShell.tsx')
  assert.match(shell, /wuxia-site-skin/)
  assert.match(shell, /wuxia-reference-skin/)
  assert.match(shell, /<CommunityIdentityProvider>/)
  assert.match(shell, /<WuxiaFooter \/>/)
  assert.match(shell, /<FeedbackWidget \/>/)
  const header = read('app/components/SiteHeader.tsx')
  assert.match(header, /<SearchCommand entries=\{searchEntries\} \/>/)
  assert.match(header, /wuxia-brand-seal/)
  for (const href of ['/skills','/guides/quests','/equipment','/systems','/tools','/updates','/forum']) assert.ok(header.includes(`href: '${href}'`))
})
test('mobile refinement only changes presentation; existing data controls and comparison remain', () => {
  const source = read('app/skills/table.tsx')
  for (const pattern of [/aria-expanded=\{filtersOpen\}/,/aria-controls=\{filtersId\}/,/data-open=\{filtersOpen\}/,/aria-pressed=\{family === v\}/,/aria-label="武技排序"/,/aria-label="武技階級"/,/selected\.map\(encodeURIComponent\)/,/setNeiliMaxCap/,/setAvgDmgMinCap/]) assert.match(source, pattern)
  const css = read('app/wuxia-reference.css')
  assert.match(css, /@media \(max-width: 1023px\)/)
  assert.match(css, /skill-refine\[data-open=false\] \{ display: none/)
  assert.match(css, /skill-filters > \.skill-refine \{ display: grid/)
})
test('inner artwork blends into the full page background, not a detached title image', () => {
  const heading = read('app/components/ReferenceHeading.tsx')
  assert.match(heading, /<h1>\{title\}<\/h1>/)
  assert.doesNotMatch(heading, /next\/image|<Image|<img|reference-chapter-art/)
  assert.match(read('app/LandingPage.tsx'), /\/art\/wuxia\/hero\.webp/)
  const css = read('app/wuxia-reference.css')
  assert.match(css, /font-size: 16px/)
  assert.match(css, /font-variant-numeric: tabular-nums/)
  assert.match(css, /\.wuxia-reference-skin::before/)
  assert.match(css, /background-image: url\('\/art\/wuxia\/hero\.webp'\)/)
  assert.match(css, /mask-image: linear-gradient/)
  assert.match(css, /pointer-events: none/)
  assert.match(css, /mix-blend-mode: multiply/)
  assert.match(css, /isolation: isolate/)
  assert.doesNotMatch(css, /radial-gradient|backdrop-filter/)
  assert.doesNotMatch(css, /reference-chapter-art/)
  const guides = read('app/guides.css')
  for (const tone of ['info','attention','danger','success']) assert.ok(guides.includes(`[data-guide-tone=${tone}]`))
  const ranges = read('app/readability.css')
  assert.match(ranges, /webkit-slider-thumb[^}]+opacity:0/)
  assert.match(ranges, /moz-range-thumb[^}]+opacity:0/)
  assert.match(ranges, /input\[type=range\]:focus-visible/)
})
test('five elements retain both relation cycles, labelled colour and accessible controls without ornamental gradients', () => {
  const source = read('app/components/FiveElementsInteractive.tsx')
  assert.match(source, /木: '火'/)
  assert.match(source, /水: '火'/)
  assert.match(source, /const SHENG_BONUS = 20/)
  assert.match(source, /const KE_PENALTY = -20/)
  assert.match(source, /aria-pressed=\{active\}/)
  assert.match(source, /h-11 w-11/)
  assert.match(source, /實線：相生/)
  assert.match(source, /虛線：相剋/)
  assert.doesNotMatch(source, /radialGradient|linearGradient|soft-shadow|bg-gradient/)
  assert.match(source, /viewBox="-16 -20 532 550"/)
})
